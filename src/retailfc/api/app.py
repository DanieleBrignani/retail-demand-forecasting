"""Forecast API.

Design decision: **the endpoint retrieves precomputed forecasts** from PostgreSQL (batch-generated by the approved
model version on a validated data snapshot). It never runs model inference or reads sales history, so latency
is storage-retrieval latency; model inference is measured separately in the batch run (see docs/operations.md).

Timeout/concurrency assumptions: each request holds one pooled connection with a statement timeout
(``request_timeout_seconds``); at most ``max_concurrency`` requests execute concurrently, excess requests get
HTTP 503 ``overloaded`` immediately instead of queueing unboundedly.
"""

from __future__ import annotations

import hmac
import json
import logging
import os
import threading
import time
import uuid
from contextlib import asynccontextmanager
from datetime import UTC, datetime

import psycopg
from fastapi import Depends, FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse, Response
from prometheus_client import CONTENT_TYPE_LATEST, CollectorRegistry, Counter, Histogram, generate_latest
from psycopg_pool import ConnectionPool
from pydantic import BaseModel, Field

from .. import config as C

log = logging.getLogger("retailfc.api")


class ForecastRequest(BaseModel):
    item_id: str = Field(min_length=1, max_length=64)
    store_id: str = Field(min_length=1, max_length=16)
    horizon: int = Field(ge=1, le=28)


class DayForecast(BaseModel):
    """One forecast. ``horizon`` counts ``horizon_unit`` (days or 7-day blocks); the covered period is explicit, so a weekly
    value can never be read as a daily one. For daily rows the period is the single ``target_date``."""

    target_date: str
    target_period_start: str
    target_period_end: str
    horizon: int
    forecast: float
    lower: float | None = None
    upper: float | None = None
    fallback_used: str = ""


class ForecastResponse(BaseModel):
    item_id: str
    store_id: str
    forecast_origin: str
    granularity: str  # 'day' | 'week'
    horizon_unit: str
    forecasts: list[DayForecast]
    model_version: str
    dataset_version: str
    feature_version: str
    forecast_batch_id: str
    generated_at: str
    fallback: dict
    mode: str


class ApiError(Exception):
    def __init__(self, status: int, code: str, message: str):
        self.status, self.code, self.message = status, code, message


def _jlog(**kw) -> None:
    log.info(json.dumps({"ts": datetime.now(UTC).isoformat(), **kw}))


MIN_KEY_LENGTH = 16


def load_api_keys(api_keys: list[str] | None = None) -> list[str]:
    """Keys come from the argument or ``RETAILFC_API_KEYS`` (comma-separated, supports rotation with two live keys).
    Weak keys are rejected at startup rather than silently accepted."""
    raw = api_keys if api_keys is not None else os.environ.get("RETAILFC_API_KEYS", "").split(",")
    keys = [k.strip() for k in raw if k and k.strip()]
    weak = [k for k in keys if len(k) < MIN_KEY_LENGTH]
    if weak:
        raise ValueError(f"API keys must be at least {MIN_KEY_LENGTH} characters ({len(weak)} too short)")
    return keys


def create_app(
    dsn: str | None = None,
    cfg: dict | None = None,
    api_keys: list[str] | None = None,
    auth_disabled: bool | None = None,
) -> FastAPI:
    """Authentication is **fail-closed**: unless keys are configured (``RETAILFC_API_KEYS``) or auth is explicitly
    disabled (``RETAILFC_API_AUTH=disabled``, development only) ``/forecast`` answers 503 ``auth_not_configured``."""
    cfg = cfg or C.load_config()
    sv = cfg["serving"]
    api_model = sv.get(
        "api_model_name", sv["model_name"]
    )  # the registry line the API serves (may differ from the daily line)
    keys = load_api_keys(api_keys)
    disabled = (
        auth_disabled
        if auth_disabled is not None
        else os.environ.get("RETAILFC_API_AUTH", "").strip().lower() == "disabled"
    )
    if disabled:
        log.warning("API authentication is DISABLED (development only)")
    auth_state = "disabled" if disabled else ("enabled" if keys else "not_configured")
    reg = CollectorRegistry()
    req_total = Counter("retailfc_api_requests_total", "Requests", ["endpoint", "status"], registry=reg)
    req_lat = Histogram(
        "retailfc_api_request_seconds",
        "API latency",
        ["endpoint"],
        registry=reg,
        buckets=(0.002, 0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5),
    )
    ret_lat = Histogram(
        "retailfc_api_retrieval_seconds",
        "Storage retrieval latency",
        registry=reg,
        buckets=(0.001, 0.002, 0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1),
    )
    sem = threading.BoundedSemaphore(sv["max_concurrency"])
    state: dict = {}

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        try:
            state["pool"] = ConnectionPool(
                dsn or C.dsn(),
                min_size=1,
                max_size=max(1, sv["max_concurrency"]),
                open=False,
                kwargs={"options": f"-c statement_timeout={int(sv['request_timeout_seconds'] * 1000)}"},
            )
            state["pool"].open(wait=False)
        except Exception as e:  # liveness stays up; readiness reports the problem
            state["pool_error"] = repr(e)
        yield
        if "pool" in state:
            state["pool"].close()

    app = FastAPI(title="Retail demand forecast API", version="0.1.0", lifespan=lifespan)

    @app.middleware("http")
    async def request_id(request: Request, call_next):
        rid = request.headers.get("x-request-id") or str(uuid.uuid4())
        request.state.rid = rid
        t0 = time.perf_counter()
        resp = await call_next(request)
        dt = time.perf_counter() - t0
        resp.headers["x-request-id"] = rid
        ep = (
            request.url.path
            if request.url.path in ("/forecast", "/health/live", "/health/ready")
            else "other"
        )
        req_total.labels(ep, str(resp.status_code)).inc()
        req_lat.labels(ep).observe(dt)
        _jlog(
            event="request",
            request_id=rid,
            path=request.url.path,
            method=request.method,
            status=resp.status_code,
            duration_ms=round(dt * 1000, 2),
        )
        return resp

    def err(request: Request, status: int, code: str, message: str) -> JSONResponse:
        return JSONResponse(
            status_code=status,
            content={
                "error": {"code": code, "message": message, "request_id": getattr(request.state, "rid", None)}
            },
        )

    @app.exception_handler(ApiError)
    async def _api_error(request: Request, exc: ApiError):
        resp = err(request, exc.status, exc.code, exc.message)
        if exc.status == 401:
            resp.headers["WWW-Authenticate"] = "ApiKey header=X-API-Key"
        return resp

    def require_api_key(request: Request) -> None:
        """Constant-time comparison against every configured key (no early exit); the key is never logged."""
        if auth_state == "disabled":
            return
        if auth_state == "not_configured":
            raise ApiError(503, "auth_not_configured", "no API keys configured; set RETAILFC_API_KEYS")
        supplied = request.headers.get("x-api-key", "").encode()
        ok = False
        for k in keys:
            ok |= hmac.compare_digest(supplied, k.encode())
        if not ok:
            _jlog(event="auth_failure", request_id=getattr(request.state, "rid", None), path=request.url.path)
            raise ApiError(401, "unauthorized", "missing or invalid API key")

    @app.exception_handler(RequestValidationError)
    async def _validation(request: Request, exc: RequestValidationError):
        rid = getattr(request.state, "rid", None)
        return JSONResponse(
            status_code=422,
            content={
                "error": {
                    "code": "invalid_request",
                    "request_id": rid,
                    "message": "; ".join(
                        f"{'.'.join(map(str, e['loc'][1:]))}: {e['msg']}" for e in exc.errors()
                    ),
                }
            },
        )

    def _conn():
        if "pool" not in state:
            raise ApiError(503, "database_unavailable", state.get("pool_error", "pool not initialised"))
        try:
            return state["pool"].connection(timeout=sv["request_timeout_seconds"])
        except Exception as e:
            raise ApiError(
                503, "database_unavailable", f"cannot obtain a database connection: {type(e).__name__}"
            ) from e

    @app.get("/health/live")
    def live():
        return {"status": "alive"}

    @app.get("/health/ready")
    def ready(request: Request):
        if auth_state == "not_configured":
            return err(request, 503, "auth_not_configured", "no API keys configured; set RETAILFC_API_KEYS")
        try:
            with _conn() as conn:
                m = conn.execute(
                    "SELECT model_version FROM app.approved_models WHERE model_name=%s AND is_current",
                    (api_model,),
                ).fetchone()
                if not m:
                    return err(request, 503, "model_unavailable", "no approved model version")
                b = conn.execute(
                    "SELECT 1 FROM app.forecast_batches WHERE model_name=%s AND model_version=%s AND status='complete' LIMIT 1",
                    (api_model, m[0]),
                ).fetchone()
                if not b:
                    return err(
                        request, 503, "no_forecast_batch", f"no complete forecast batch for model v{m[0]}"
                    )
            return {"status": "ready", "model_version": m[0], "auth": auth_state}
        except ApiError as e:
            return err(request, e.status, e.code, e.message)
        except psycopg.Error as e:
            return err(request, 503, "database_unavailable", type(e).__name__)

    @app.post("/forecast", response_model=ForecastResponse, dependencies=[Depends(require_api_key)])
    def forecast(req: ForecastRequest, request: Request):
        if not sem.acquire(blocking=False):
            raise ApiError(503, "overloaded", f"more than {sv['max_concurrency']} concurrent requests")
        try:
            t0 = time.perf_counter()
            try:
                with _conn() as conn:
                    m = conn.execute(
                        "SELECT model_version, dataset_version FROM app.approved_models "
                        "WHERE model_name=%s AND is_current",
                        (api_model,),
                    ).fetchone()
                    if not m:
                        raise ApiError(503, "model_unavailable", "no approved model version is configured")
                    b = conn.execute(
                        "SELECT forecast_batch_id, forecast_origin, generation_time, dataset_version, feature_version, mode, granularity "
                        "FROM app.forecast_batches WHERE model_name=%s AND model_version=%s AND status='complete' "
                        "ORDER BY forecast_origin DESC, generation_time DESC LIMIT 1",
                        (api_model, m[0]),
                    ).fetchone()
                    if not b:
                        raise ApiError(
                            503, "no_forecast_batch", f"approved model v{m[0]} has no complete forecast batch"
                        )
                    max_h = 4 if b[6] == "week" else 28
                    if req.horizon > max_h:
                        raise ApiError(
                            422,
                            "horizon_out_of_range",
                            f"this model serves {b[6]}ly forecasts: horizon must be 1..{max_h} {b[6]}(s)",
                        )
                    rows = conn.execute(
                        "SELECT target_date, horizon, forecast_value, lower_bound, upper_bound, fallback_used, "
                        "target_period_start, target_period_end "
                        "FROM app.forecasts WHERE forecast_batch_id=%s AND item_id=%s AND store_id=%s AND horizon<=%s "
                        "ORDER BY horizon",
                        (b[0], req.item_id, req.store_id, req.horizon),
                    ).fetchall()
            except ApiError:
                raise
            except psycopg.Error as e:
                raise ApiError(503, "database_unavailable", f"{type(e).__name__}") from e
            ret_lat.observe(time.perf_counter() - t0)
            if not rows:
                raise ApiError(
                    404,
                    "unknown_series",
                    f"no forecasts for item_id={req.item_id!r}, store_id={req.store_id!r} "
                    f"in the active batch",
                )
            fbs = {r[5] for r in rows if r[5]}
            return ForecastResponse(
                item_id=req.item_id,
                store_id=req.store_id,
                forecast_origin=b[1].isoformat(),
                granularity=b[6],
                horizon_unit=b[6],
                forecasts=[
                    DayForecast(
                        target_date=r[0].isoformat(),
                        target_period_start=r[6].isoformat(),
                        target_period_end=r[7].isoformat(),
                        horizon=r[1],
                        forecast=r[2],
                        lower=r[3],
                        upper=r[4],
                        fallback_used=r[5],
                    )
                    for r in rows
                ],
                model_version=m[0],
                dataset_version=b[3],
                feature_version=b[4],
                forecast_batch_id=b[0],
                generated_at=b[2].isoformat(),
                mode=b[5],
                fallback={
                    "used": bool(fbs),
                    "reasons": sorted(fbs),
                    "horizons": [r[1] for r in rows if r[5]],
                },
            )
        finally:
            sem.release()

    @app.get("/metrics")
    def metrics():
        return Response(generate_latest(reg), media_type=CONTENT_TYPE_LATEST)

    return app


def app_factory() -> FastAPI:  # uvicorn --factory retailfc.api.app:app_factory
    return create_app()
