"""Build result tables/charts strictly from stored experiment outputs. Missing outputs => section marked PENDING."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from . import analysis  # noqa: E402
from . import config as C  # noqa: E402
from . import experiments as E  # noqa: E402
from .backtesting import runner as R  # noqa: E402

PENDING = (
    "**PENDING** - this experiment stage has not been executed on the real data; no numbers are reported."
)


def _md(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    return df.to_markdown(index=False, floatfmt=floatfmt) if len(df) else "_(empty)_"


def _pooled(met: pd.DataFrame, **flt) -> pd.DataFrame:
    m = met[(met.aggregation == "pooled")]
    for k, v in flt.items():
        m = m[m[k] == v] if v is not None else m[m[k].isna()]
    return m


def build_report(experiment_id: str, out: Path | None = None) -> dict:
    exp = E.experiment_dir(experiment_id)
    out = Path(out or C.home() / "reports" / experiment_id)
    out.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# Results: `{experiment_id}`\n",
        "_Generated by `retailfc report build` from stored outputs; never hand-edited._\n",
    ]
    status = {}
    v = exp / "validation"
    if not (v / "metrics.parquet").exists():
        lines += ["## Validation\n", PENDING]
        (out / "results.md").write_text("\n".join(lines), encoding="utf-8")
        return {"status": "pending", "out": str(out)}
    meta = json.loads((v / "run_meta.json").read_text())
    met = pd.read_parquet(v / "metrics.parquet")
    lines += [
        f"Dataset `{meta['dataset_version']}`; validation origins {meta['origins']['validation']}; holdout origin "
        f"{meta['origins']['holdout']} (not used here). Series: {meta['n_series']}.\n",
        "WAPE = sum|f-a|/sum|a| (pooled; dominated by high-volume series). Bias sign: forecast - actual.\n",
    ]

    def stage(name: str, d: Path, mt: pd.DataFrame):
        lines.append(f"\n## {name}\n")
        for scope in ("full_panel", "restricted_subset"):
            sub = mt[mt.evaluation_scope == scope]
            if sub.empty:
                continue
            allr = _pooled(sub, segment_type="all", horizon="1-28", forecast_origin=None)
            tab = allr.pivot_table(index="model_name", columns="metric", values="value")
            tab = tab[
                [c for c in ("wape", "mae", "rmse", "smape", "bias", "bias_pct") if c in tab]
            ].sort_values("wape")
            lines.append(
                f"\n### Pooled metrics, scope `{scope}` (horizons 1-28, all origins)\n\n{_md(tab.reset_index())}\n"
            )
            tab.to_csv(out / f"{d.name}_{scope}_overall.csv")
            po = _pooled(sub, segment_type="all", horizon="1-28", metric="wape")
            po = po[po.forecast_origin.notna()].pivot_table(
                index="model_name", columns="forecast_origin", values="value"
            )
            lines.append(
                f"\n**Per-origin WAPE** (origin-level variability, scope `{scope}`)\n\n{_md(po.reset_index())}\n"
            )
            hz = _pooled(sub, segment_type="all", metric="wape", forecast_origin=None)
            hz = (
                hz[hz.horizon.str.fullmatch(r"\d+")]
                .assign(h=lambda x: x.horizon.astype(int))
                .pivot_table(index="h", columns="model_name", values="value")
            )
            hz.to_csv(out / f"{d.name}_{scope}_wape_by_horizon.csv")
            if scope == "full_panel":
                fig, ax = plt.subplots(figsize=(7, 4))
                hz.plot(ax=ax)
                ax.set(title=f"WAPE by horizon ({d.name})", ylabel="WAPE")
                fig.tight_layout()
                fig.savefig(out / f"{d.name}_wape_by_horizon.png", dpi=110)
                plt.close(fig)
                for st in ("volume", "intermittency", "store", "state", "category"):
                    s = _pooled(sub, segment_type=st, horizon="1-28", metric="wape", forecast_origin=None)
                    if len(s):
                        lines.append(
                            f"\n**WAPE by {st}**\n\n{_md(s.pivot_table(index='segment_value', columns='model_name', values='value').reset_index())}\n"
                        )
                        s.pivot_table(index="segment_value", columns="model_name", values="value").to_csv(
                            out / f"{d.name}_wape_by_{st}.csv"
                        )
        und = met[(met.metric == "wape") & (met.undefined)] if "undefined" in met else pd.DataFrame()
        lines.append(f"\nUndefined WAPE cells (zero denominator): {len(und)}\n")

    stage("Validation results (all models reported)", v, met)
    tim = pd.read_csv(v / "timings.csv")
    tt = (
        tim.groupby("model")
        .agg(
            fit_s_total=("fit_seconds", "sum"),
            predict_s_total=("predict_seconds", "sum"),
            predict_s_mean=("predict_seconds", "mean"),
        )
        .reset_index()
    )
    lines.append(f"\n### Runtime (this machine; see `environment` in run_meta)\n\n{_md(tt)}\n")
    pred = R.load_predictions(v)
    pcs = []
    for ref in ("seasonal_naive", "naive"):
        for m in sorted(set(pred.model_name) - {ref}):
            if m == "sarima":
                continue
            r = analysis.paired_vs_reference(pred, m, ref)
            pcs.append(
                {
                    "model": m,
                    "reference": ref,
                    "n_matched": r["n_matched"],
                    "mean_delta_wape": r["mean_delta_wape"],
                    "min_delta": r["min_delta"],
                    "max_delta": r["max_delta"],
                    "origins_model_better": f"{r['origins_model_better']}/{r['n_origins']}",
                    "share_series_better(descriptive)": r["share_series_model_better_descriptive"],
                }
            )
    pc = pd.DataFrame(pcs)
    pc.to_csv(out / "paired_vs_baselines.csv", index=False)
    lines.append(
        "\n### Paired comparison on matched observations (delta = model - reference WAPE; negative is better)\n\n"
        "No significance claim: observations are dependent across series, horizons and (if overlapping) windows.\n\n"
        + _md(pc)
        + "\n"
    )
    lines.append("\n### Error analysis tables\n")
    try:
        from .panel import load_panel_from_raw

        panel = load_panel_from_raw(meta["dataset_version"])
        ea = out / "error_analysis"
        ea.mkdir(exist_ok=True)
        counts = {}
        for m in sorted(set(pred.model_name) & {"seasonal_naive", "lgbm_A", "lgbm_B", "lgbm_C", "lgbm_D"}):
            counts[m] = analysis.error_tables(pred, panel, m, ea)
        lines.append(
            f"Tables written to `{ea.name}/` (largest errors, horizon degradation, segments, fallback performance, event periods, "
            f"price-change periods, history length). Persistent over/under-forecast series (same sign at every origin, series with >=2 origins): "
            f"{json.dumps(counts)}\n"
        )
    except Exception as e:  # raw data not present on this machine, etc.
        lines.append(f"Error-analysis tables not generated: {type(e).__name__}: {e}\n")
    sel = exp / "selection.json"
    if sel.exists():
        s = json.loads(sel.read_text())
        ab = pd.DataFrame(s["log"])
        lines.append(
            f"\n## Feature ablation (validation only)\n\nSelected set: **{s['selected_feature_set']}** (adoption needs >= {s['min_gain']:.1%} relative WAPE gain).\n\n{_md(ab)}\n"
        )
    status["validation"] = "done"
    h = exp / "holdout"
    if (h / "metrics.parquet").exists():
        stage("Final holdout (single locked evaluation)", h, pd.read_parquet(h / "metrics.parquet"))
        status["holdout"] = "done"
    else:
        lines += ["\n## Final holdout\n", PENDING]
        status["holdout"] = "pending"
    for name, fn, label in (
        ("uncertainty", "summary.json", "Prediction intervals"),
        ("interpretability", "summary.json", "Interpretability"),
    ):
        p = exp / name / fn
        lines.append(f"\n## {label}\n")
        if p.exists():
            lines.append("```json\n" + p.read_text() + "\n```\n")
            status[name] = "done"
        else:
            lines.append(PENDING)
            status[name] = "pending"
    (out / "results.md").write_text("\n".join(lines), encoding="utf-8")
    return {"status": status, "out": str(out)}
